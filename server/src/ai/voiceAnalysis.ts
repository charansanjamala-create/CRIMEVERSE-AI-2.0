// VoiceShield AI — Mock Voice Cloning Detection Service
// IMPORTANT: This is a demo/mock implementation.
// AI output is an INDICATOR only. Human review is always required.

export interface VoiceAnalysisResult {
  suspicionScore: number;
  riskLevel: string;
  verdict: string;
  indicators: { name: string; description: string; severity: string; confidence: number }[];
  spectralAnalysis: Record<string, any>;
  temporalFeatures: Record<string, any>;
  modelFindings: string[];
  disclaimer: string;
  requiresHumanReview: boolean;
}

function generateDemoResult(fileName: string, seed?: number): VoiceAnalysisResult {
  // Deterministic but varied results based on filename
  const hash = Array.from(fileName).reduce((acc, c) => acc + c.charCodeAt(0), seed || 42);
  const score = 30 + (hash % 55); // 30–85 range for demo

  const riskLevel = score >= 75 ? 'HIGH' : score >= 55 ? 'MEDIUM' : score >= 35 ? 'LOW' : 'MINIMAL';

  const allIndicators = [
    { name: 'Spectral Inconsistency', description: 'Unusual frequency distribution patterns detected in vocal range', severity: 'HIGH', confidence: 78 },
    { name: 'Pitch Modulation Anomaly', description: 'Irregular pitch variance inconsistent with natural speech patterns', severity: 'MEDIUM', confidence: 65 },
    { name: 'Background Noise Discontinuity', description: 'Sudden changes in ambient noise levels suggest audio splicing', severity: 'MEDIUM', confidence: 71 },
    { name: 'Formant Trajectory Deviation', description: 'Vowel formant transitions deviate from expected natural patterns', severity: 'HIGH', confidence: 82 },
    { name: 'Temporal Jitter', description: 'Micro-timing irregularities suggest synthetic generation', severity: 'LOW', confidence: 55 },
    { name: 'Mel-Frequency Cepstral Anomaly', description: 'MFCC features show statistical outliers consistent with TTS generation', severity: 'HIGH', confidence: 76 },
    { name: 'Breathing Pattern Analysis', description: 'Absence of natural breathing patterns between phrases', severity: 'MEDIUM', confidence: 68 },
  ];

  const indicatorCount = score >= 75 ? 4 : score >= 55 ? 3 : score >= 35 ? 2 : 1;
  const indicators = allIndicators.slice(0, indicatorCount).map(ind => ({
    ...ind,
    confidence: ind.confidence + ((hash % 10) - 5),
  }));

  const verdict =
    score >= 75
      ? 'POSSIBLE SYNTHETIC VOICE — Requires immediate human review'
      : score >= 55
      ? 'SUSPICIOUS INDICATORS DETECTED — Review recommended'
      : score >= 35
      ? 'MINOR ANOMALIES — Low suspicion, monitoring advised'
      : 'NO SIGNIFICANT SYNTHETIC INDICATORS — Appears natural';

  return {
    suspicionScore: Math.min(100, score),
    riskLevel,
    verdict,
    indicators,
    spectralAnalysis: {
      fundamentalFrequency: { mean: 120 + (hash % 80), std: 12 + (hash % 8), unit: 'Hz' },
      harmonicToNoiseRatio: { value: 15 - (score / 10), unit: 'dB' },
      spectralFlux: { value: 0.3 + (score / 200), anomalous: score > 60 },
      formantF1: { mean: 500 + (hash % 200), unit: 'Hz' },
      formantF2: { mean: 1500 + (hash % 500), unit: 'Hz' },
    },
    temporalFeatures: {
      speechRate: { value: 4.2 + (hash % 3), unit: 'syllables/sec', anomalous: score > 70 },
      pauseDuration: { mean: 0.2 + (score / 500), std: 0.05, unit: 'sec' },
      voicedFrameRatio: { value: 0.6 + (hash % 30) / 100 },
      jitterLocal: { value: (1 + (score / 30)).toFixed(3) + '%', threshold: '2%', flagged: score > 60 },
    },
    modelFindings: [
      `VoiceClone Detector v2.3: Probability of synthetic origin — ${score}%`,
      `GAN Artifact Scanner: ${score > 60 ? 'Artifacts detected in' : 'No significant artifacts in'} frequency domain`,
      `WaveNet Pattern Analysis: ${score > 70 ? 'High similarity to known TTS patterns' : 'Patterns within natural speech range'}`,
      'IMPORTANT: AI analysis is an indicator only — not conclusive evidence',
    ],
    disclaimer:
      'This analysis is generated by a demo AI service and is intended as an investigative indicator only. Results must not be used as conclusive evidence. Human expert review is mandatory before any action is taken. The AI system may produce false positives and false negatives.',
    requiresHumanReview: true,
  };
}

export async function analyzeVoice(fileName: string, fileBuffer?: Buffer): Promise<VoiceAnalysisResult> {
  // Simulate async processing
  await new Promise(resolve => setTimeout(resolve, 1200));
  return generateDemoResult(fileName);
}

export async function analyzeVoiceDemo(type: 'high' | 'medium' | 'low' = 'medium'): Promise<VoiceAnalysisResult> {
  const seeds = { high: 99, medium: 55, low: 10 };
  await new Promise(resolve => setTimeout(resolve, 800));
  return generateDemoResult(`demo_audio_${type}.wav`, seeds[type]);
}
